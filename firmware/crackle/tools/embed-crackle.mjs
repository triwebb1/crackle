#!/usr/bin/env node
// Embeds the Crackle production bundle (web/dist) into the controller sketch as gzip-compressed
// PROGMEM arrays, so the ESP32 serves the app same-origin.
//
//   node firmware/crackle/tools/embed-crackle.mjs [--dist web/dist] [--package web/package.json] [--out path]
//
// Run after `npm --prefix web run build` (or use `npm --prefix web run embed`, which does both).
// Output is deterministic: gzip carries no timestamp and a fixed OS byte, so identical inputs give a
// byte-identical header on every platform with the same Node release.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { constants, gzipSync } from 'node:zlib'

const toolsDirectory = dirname(fileURLToPath(import.meta.url))
const repositoryRoot = resolve(toolsDirectory, '../../..')

const option = (name, fallback) => {
  const index = process.argv.indexOf(`--${name}`)
  return index >= 0 && process.argv[index + 1] ? resolve(process.argv[index + 1]) : fallback
}
const distRoot = option('dist', join(repositoryRoot, 'web/dist'))
const packageJsonPath = option('package', join(repositoryRoot, 'web/package.json'))
const outputPath = option('out', join(repositoryRoot, 'firmware/crackle/crackle/crackle_bundle.h'))

const fail = (message) => {
  console.error(`embed-crackle: ${message}`)
  process.exit(1)
}

if (!existsSync(distRoot) || !statSync(distRoot).isDirectory()) fail(`dist directory not found: ${distRoot}`)
if (!existsSync(packageJsonPath)) fail(`package.json not found: ${packageJsonPath}`)

const { version } = JSON.parse(readFileSync(packageJsonPath, 'utf8'))
if (typeof version !== 'string' || !/^[0-9A-Za-z.\-+]{1,32}$/.test(version)) {
  fail(`refusing to embed an unexpected version string: ${version}`)
}

const listFiles = (directory) => readdirSync(directory, { withFileTypes: true })
  .flatMap((entry) => entry.isDirectory() ? listFiles(join(directory, entry.name)) : [join(directory, entry.name)])
  .sort()

// The sketch serves exactly three files. Anything else means the Vite output shape changed (code
// splitting, extra chunks, fonts, icons) and the sketch's serving routes would silently stop matching.
const allFiles = listFiles(distRoot)
if (allFiles.length !== 3) {
  fail(`expected exactly 3 files in web/dist (index.html + one js + one css); found ${allFiles.length}: ${allFiles.map((file) => relative(distRoot, file)).join(', ')}`)
}
const indexFile = join(distRoot, 'index.html')
if (!allFiles.includes(indexFile)) fail('web/dist/index.html not found.')
const assetFiles = allFiles.filter((file) => dirname(file) === join(distRoot, 'assets'))
if (assetFiles.length !== 2) fail(`expected exactly 2 files in web/dist/assets; found ${assetFiles.length}.`)

const fileName = (file) => file.slice(dirname(file).length + 1)
const scriptFile = assetFiles.find((file) => /^index-[A-Za-z0-9_-]+\.js$/.test(fileName(file)))
const styleFile = assetFiles.find((file) => /^index-[A-Za-z0-9_-]+\.css$/.test(fileName(file)))
if (!scriptFile) fail('no asset matched the expected hashed script pattern index-<hash>.js.')
if (!styleFile) fail('no asset matched the expected hashed stylesheet pattern index-<hash>.css.')

// The generated routes hard-code these paths; index.html must actually ask for them or the served
// page would load nothing.
const indexHtml = readFileSync(indexFile, 'utf8')
for (const asset of [scriptFile, styleFile]) {
  if (!indexHtml.includes(`/assets/${fileName(asset)}`)) fail(`web/dist/index.html does not reference /assets/${fileName(asset)}.`)
}

const GZIP_OS_BYTE = 9
const GZIP_OS_UNKNOWN = 0xff
const compress = (bytes) => {
  const compressed = gzipSync(bytes, { level: constants.Z_BEST_COMPRESSION, memLevel: 9 })
  compressed[GZIP_OS_BYTE] = GZIP_OS_UNKNOWN
  return compressed
}

const formatBytes = (bytes) => {
  const lines = []
  for (let offset = 0; offset < bytes.length; offset += 16) {
    lines.push(`    ${[...bytes.subarray(offset, offset + 16)].map((byte) => `0x${byte.toString(16).padStart(2, '0')},`).join(' ')}\n`)
  }
  return lines.join('')
}

const assets = [
  { symbol: 'Index', file: indexFile, path: '/', contentType: 'text/html' },
  { symbol: 'Script', file: scriptFile, path: `/assets/${fileName(scriptFile)}`, contentType: 'text/javascript' },
  { symbol: 'Style', file: styleFile, path: `/assets/${fileName(styleFile)}`, contentType: 'text/css' },
]

let header = `// Generated by tools/embed-crackle.mjs -- do not edit by hand.
// Crackle ${version} production bundle, gzip-compressed, served same-origin by
// the Crackle web server. Regenerate after every web production build.
#pragma once

#include <Arduino.h>
#include <stddef.h>
#include <stdint.h>

namespace sr800 {
namespace crackle {

constexpr char kCrackleBundleVersion[] = "${version}";

`
const summary = []
for (const asset of assets) {
  const raw = readFileSync(asset.file)
  const compressed = compress(raw)
  header += `
constexpr char k${asset.symbol}Path[] = "${asset.path}";
constexpr char k${asset.symbol}ContentType[] = "${asset.contentType}";
constexpr char k${asset.symbol}FileName[] = "${fileName(asset.file)}";
const uint8_t k${asset.symbol}Gz[] PROGMEM = {
${formatBytes(compressed)}};
constexpr size_t k${asset.symbol}GzLength = sizeof(k${asset.symbol}Gz);

`
  summary.push({ name: fileName(asset.file), raw: raw.length, gzip: compressed.length })
}
header += `
}  // namespace crackle
}  // namespace sr800
`

if (!existsSync(dirname(outputPath))) fail(`output directory does not exist: ${dirname(outputPath)}`)
writeFileSync(outputPath, header)

console.log(`Crackle bundle version: ${version}`)
for (const entry of summary) console.log(`  ${entry.name}: ${entry.raw} B -> ${entry.gzip} B gzip`)
console.log(`Total: ${summary.reduce((sum, entry) => sum + entry.raw, 0)} B -> ${summary.reduce((sum, entry) => sum + entry.gzip, 0)} B gzip`)
console.log(`Wrote: ${outputPath}`)
