import { describe, expect, it } from 'vitest'
import { defaultCalibration } from '../data/calibration'
import { richDemoDataset } from '../data/demoDataset'
import {
  baselinePinnedAirflow,
  COEFFICIENT_BOUNDS,
  combineSegmentedCalibration,
  estimateAmbientC,
  fitAgainstBaseline,
  fitCoefficientsFromLog,
  fitSourceFromRun,
  heatingAirflowResolved,
  isLoadedRun,
  logExcitation,
  pooledRms,
  unresolvedUnstableFields,
} from './coefficientFit'
import { modelFitVerdict, replayCalibrationRun, replayThermalLog } from './modelFit'
import { thermalStep } from './thermalModel'
import type { CalibrationSettings, ThermalSample } from './types'

const AMBIENT = 21

/** A log generated BY the model, so the fit has a known answer to find. */
const syntheticLog = (
  calibration: CalibrationSettings,
  massG: number,
  steps: Array<{ fan: number; heat: number; seconds: number }>,
): ThermalSample[] => {
  const samples: ThermalSample[] = []
  let temperatureC = AMBIENT
  let rorCPerMin: number | undefined
  let seconds = 0
  samples.push({
    tMs: 0,
    thermocoupleC: temperatureC,
    coldJunctionC: AMBIENT,
    effectiveFan: steps[0].fan,
    effectiveHeat: steps[0].heat,
  })
  for (const step of steps) {
    for (let second = 0; second < step.seconds; second += 1) {
      const result = thermalStep(
        {
          previousBeanTempC: temperatureC,
          previousRorCPerMin: rorCPerMin,
          fan: step.fan,
          heat: step.heat,
          cooling: step.heat === 0,
          batchMassG: massG,
          ambientC: AMBIENT,
        },
        calibration,
      )
      temperatureC = result.beanTempC
      rorCPerMin = result.rorCPerMin
      seconds += 1
      samples.push({
        tMs: seconds * 1000,
        thermocoupleC: temperatureC,
        coldJunctionC: AMBIENT,
        effectiveFan: step.fan,
        effectiveHeat: step.heat,
      })
    }
  }
  return samples
}

const TRUTH = {
  ...defaultCalibration,
  heaterGainCPerMinAt10: 58,
  fanCoolingCPerMinAt10: 26,
  coolingFanCPerMinAt10: 34,
  thermalLossPerMinPerC: 0.21,
}

/** A roast driven the way the Calibrate guide says to drive one. */
const EXCITED = [
  { fan: 4, heat: 7, seconds: 150 },
  { fan: 9, heat: 7, seconds: 150 },
  { fan: 4, heat: 7, seconds: 120 },
  { fan: 6, heat: 4, seconds: 150 },
  { fan: 6, heat: 9, seconds: 150 },
  { fan: 9, heat: 0, seconds: 180 },
]
/** A roast where fan and heat only ever move together, which cannot separate them. */
const PLAIN = [
  { fan: 8, heat: 8, seconds: 240 },
  { fan: 7, heat: 7.5, seconds: 180 },
  { fan: 6, heat: 7, seconds: 180 },
  { fan: 10, heat: 0, seconds: 240 },
]

describe('recovering known coefficients from a synthetic log', () => {
  const source = { id: 'x', label: 'x', samples: syntheticLog(TRUTH, 225, EXCITED), massG: 225, ambientC: AMBIENT }
  const fit = fitCoefficientsFromLog([source], defaultCalibration)!

  it('gets close to the truth from a properly excited roast', () => {
    for (const field of [
      'heaterGainCPerMinAt10',
      'fanCoolingCPerMinAt10',
      'coolingFanCPerMinAt10',
      'thermalLossPerMinPerC',
    ] as const) {
      const relative = Math.abs(fit.coefficients[field] - TRUTH[field]) / TRUTH[field]
      expect(relative, `${field}: fitted ${fit.coefficients[field]} vs true ${TRUTH[field]}`).toBeLessThan(0.2)
    }
  })

  it('drives the replay error down to near nothing', () => {
    expect(fit.startingRmsC).toBeGreaterThan(20)
    expect(fit.rmsC).toBeLessThan(2)
    expect(fit.rmsC).toBeLessThan(fit.startingRmsC / 10)
  })

  it('escapes a poor applied value at the controller lower bound', () => {
    const poorStart = { ...defaultCalibration, fanCoolingCPerMinAt10: COEFFICIENT_BOUNDS.fanCoolingCPerMinAt10.min }
    const recovered = fitCoefficientsFromLog([source], poorStart)!
    expect(recovered.coefficients.fanCoolingCPerMinAt10).toBeGreaterThan(10)
    expect(recovered.coefficients.fanCoolingCPerMinAt10).toBeLessThan(60)
    expect(recovered.rmsC).toBeLessThan(3)
  })

  it('reports what it did and stays inside the physical bounds', () => {
    expect(fit.sources).toBe(1)
    expect(fit.sweeps).toBeGreaterThan(0)
    expect(fit.pinned).toEqual([])
    expect(fit.unstable).toEqual([])
    for (const [field, value] of Object.entries(fit.coefficients)) {
      const bounds = COEFFICIENT_BOUNDS[field as keyof typeof COEFFICIENT_BOUNDS]
      expect(value).toBeGreaterThanOrEqual(bounds.min)
      expect(value).toBeLessThanOrEqual(bounds.max)
    }
  })

  it('fits several roasts jointly by pooling their residuals', () => {
    const second = { id: 'y', label: 'y', samples: syntheticLog(TRUTH, 180, EXCITED), massG: 180, ambientC: AMBIENT }
    const joint = fitCoefficientsFromLog([source, second], defaultCalibration)!
    expect(joint.sources).toBe(2)
    expect(joint.perSource).toHaveLength(2)
    for (const entry of joint.perSource) expect(entry.fit!.rmsC).toBeLessThan(6)
    expect(joint.rmsC).toBeLessThan(6)
  })

  it('never returns NaN from a non-finite base coefficient', () => {
    // Regression: `clampTo(NaN)` was NaN, so a NaN base loss came back as a NaN "fit" with a NaN RMS.
    for (const bad of [Number.NaN, Number.POSITIVE_INFINITY]) {
      const recovered = fitCoefficientsFromLog([source], { ...defaultCalibration, thermalLossPerMinPerC: bad })
      expect(recovered).toBeDefined()
      for (const value of Object.values(recovered!.coefficients)) expect(Number.isFinite(value)).toBe(true)
      expect(Number.isNaN(recovered!.rmsC)).toBe(false)
      expect(Number.isNaN(recovered!.startingRmsC)).toBe(false)
      expect(recovered!.rmsC).toBeLessThan(3)
    }
  })

  it('declines a set of logs with nothing readable in it', () => {
    expect(fitCoefficientsFromLog([], defaultCalibration)).toBeUndefined()
    expect(fitCoefficientsFromLog([{ id: 'e', label: 'e', samples: [] }], defaultCalibration)).toBeUndefined()
  })
})

/**
 * A fit is only as good as the excitation in the log, and a confident number from an unexciting one
 * is the trap this whole flow exists to avoid.
 */
describe('what a log can and cannot constrain', () => {
  it('passes a properly driven roast without complaint', () => {
    const excitation = logExcitation(syntheticLog(TRUTH, 225, EXCITED))
    expect(excitation.fanSweptAtConstantHeat).toBe(true)
    expect(excitation.hasCoolingTail).toBe(true)
    expect(excitation.warnings).toEqual([])
  })

  it('warns when fan and heat only ever moved together', () => {
    const excitation = logExcitation(syntheticLog(TRUTH, 225, PLAIN))
    expect(excitation.fanSweptAtConstantHeat).toBe(false)
    expect(excitation.warnings.join(' ')).toContain('cannot be told apart')
  })

  it('warns when nothing moved at all, or the cooling tail is missing', () => {
    const flat = logExcitation(syntheticLog(TRUTH, 225, [{ fan: 7, heat: 7, seconds: 300 }]))
    expect(flat.warnings.join(' ')).toContain('Heat never changed')
    expect(flat.warnings.join(' ')).toContain('No fan-on cooling tail')
  })

  /** The trap, demonstrated: a tiny RMS from a log that cannot identify the coefficients. */
  it('can reach a small RMS on an unexciting log with the wrong coefficients', () => {
    const fit = fitCoefficientsFromLog(
      [{ id: 'p', label: 'p', samples: syntheticLog(TRUTH, 225, PLAIN), massG: 225, ambientC: AMBIENT }],
      defaultCalibration,
    )!
    expect(fit.rmsC).toBeLessThan(2)
    const wrongBy =
      Math.abs(fit.coefficients.heaterGainCPerMinAt10 - TRUTH.heaterGainCPerMinAt10) / TRUTH.heaterGainCPerMinAt10
    expect(wrongBy).toBeGreaterThan(0.1)
    expect(fit.excitation.warnings.length).toBeGreaterThan(0)
    expect(fit.unstable.length).toBeGreaterThan(0)
  })
})

describe('loaded roasts versus chamber passes', () => {
  const dataset = richDemoDataset()
  const loaded = dataset.calibrationRuns.find(isLoadedRun)!
  const chamber = dataset.calibrationRuns.find((run) => !isLoadedRun(run))!

  it('marks a run loaded exactly when it recorded its batch', () => {
    expect(isLoadedRun(loaded)).toBe(true)
    expect(isLoadedRun(chamber)).toBe(false)
    expect(fitSourceFromRun(loaded, 'l').massG).toBe(loaded.massG)
    expect(fitSourceFromRun(chamber, 'c').massG).toBeUndefined()
  })

  it('improves the replay on the demo loaded roast over the estimated baseline', () => {
    const before = replayCalibrationRun(loaded, defaultCalibration)!
    const fit = fitCoefficientsFromLog([fitSourceFromRun(loaded, 'loaded')], defaultCalibration)!
    expect(fit.rmsC).toBeLessThan(before.rmsC)
    expect(fit.rmsC).toBeLessThan(10)
  })

  /**
   * Fitting a chamber log is allowed - the loaded flag is just an ingest choice - but it lands in
   * the poor-fit warning path rather than quietly becoming the applied model.
   */
  it('fits a chamber log into the poor-fit path rather than a usable answer', () => {
    const fit = fitCoefficientsFromLog([fitSourceFromRun(chamber, 'chamber')], defaultCalibration)!
    expect(fit.rmsC).toBeGreaterThan(20)
    expect(modelFitVerdict({ ...replayCalibrationRun(chamber, defaultCalibration)!, rmsC: fit.rmsC }).grade).toBe(
      'poor',
    )
  })

  it('scores a pool the same way whichever route the numbers arrive by', () => {
    const source = fitSourceFromRun(loaded, 'l')
    const direct = pooledRms([source], defaultCalibration)!
    const replayed = replayThermalLog(loaded.samples, defaultCalibration, {
      ambientC: source.ambientC,
      batchMassG: source.massG,
      scoreFromSec: source.scoreFromSec,
    })!.rmsC
    expect(direct).toBeCloseTo(replayed, 6)
  })

  it('uses the cool late-tail junction reading instead of a heat-soaked boot reading', () => {
    const samples = Array.from({ length: 10 }, (_, index) => ({
      ...loaded.samples[0],
      coldJunctionC: index === 9 ? 29 : 39,
    }))
    expect(estimateAmbientC(samples)).toBe(29)
  })

  it('falls back to the coolest junction reading anywhere before resorting to the constant', () => {
    const samples = Array.from({ length: 10 }, (_, index) => ({
      ...loaded.samples[0],
      coldJunctionC: index < 3 ? 31 - index : undefined,
    }))
    expect(estimateAmbientC(samples)).toBe(29)
    expect(
      estimateAmbientC(
        samples.map((sample) => ({ ...sample, coldJunctionC: undefined })),
        24.5,
      ),
    ).toBe(24.5)
  })
})

describe('segmented baseline and loaded-roast evidence', () => {
  const source = { id: 'x', label: 'x', samples: syntheticLog(TRUTH, 225, EXCITED), massG: 225, ambientC: AMBIENT }
  const fit = fitCoefficientsFromLog([source], defaultCalibration)!

  it('pins heat-off airflow but keeps heating-mode airflow the roast resolved', () => {
    const baseline = { fanCoolingCPerMinAt10: 12, coolingFanCPerMinAt10: 44, thermalLossPerMinPerC: 0.9 }
    expect(heatingAirflowResolved(fit)).toBe(true)
    const combined = combineSegmentedCalibration(fit, baseline)
    expect(combined.fanCoolingCPerMinAt10).toBe(fit.coefficients.fanCoolingCPerMinAt10)
    expect(combined.coolingFanCPerMinAt10).toBe(44)
    expect(combined.heaterGainCPerMinAt10).toBe(fit.coefficients.heaterGainCPerMinAt10)
    expect(combined.thermalLossPerMinPerC).toBe(fit.coefficients.thermalLossPerMinPerC)
  })

  it('pins baseline heating-mode airflow when the roast never separated Fan from Heat', () => {
    const plain = fitCoefficientsFromLog(
      [{ id: 'p', label: 'p', samples: syntheticLog(TRUTH, 225, PLAIN), massG: 225, ambientC: AMBIENT }],
      defaultCalibration,
    )!
    expect(heatingAirflowResolved(plain)).toBe(false)
    expect(combineSegmentedCalibration(plain, { fanCoolingCPerMinAt10: 12 }).fanCoolingCPerMinAt10).toBe(12)
  })

  it('freezes baseline airflow during the search so the free terms compensate against them', () => {
    const baseline = { fanCoolingCPerMinAt10: 12, coolingFanCPerMinAt10: 44 }
    const pinnedFit = fitCoefficientsFromLog([source], defaultCalibration, { frozen: baselinePinnedAirflow(baseline) })!
    // The frozen values come back exactly, and are never reported as search-bound collisions.
    expect(pinnedFit.coefficients.fanCoolingCPerMinAt10).toBe(12)
    expect(pinnedFit.coefficients.coolingFanCPerMinAt10).toBe(44)
    expect(pinnedFit.pinned).not.toContain('fanCoolingCPerMinAt10')
    expect(pinnedFit.pinned).not.toContain('coolingFanCPerMinAt10')
    expect(pinnedFit.unstable).not.toContain('fanCoolingCPerMinAt10')
    // The free terms adapted to the pinned airflow rather than to their own airflow estimate: the
    // reported RMS describes exactly the returned set, so combine is a no-op and nothing about the
    // saved patch was left unmeasured. Wrong pinned airflow cannot score better than the free fit.
    expect(pooledRms([source], { ...defaultCalibration, ...pinnedFit.coefficients })).toBeCloseTo(pinnedFit.rmsC, 6)
    expect(pinnedFit.rmsC).toBeGreaterThan(fit.rmsC)
    expect(combineSegmentedCalibration(pinnedFit, baseline)).toEqual(pinnedFit.coefficients)
  })

  it('pins an out-of-bounds baseline value at the nearest applicable value everywhere', () => {
    // Scored clamped but saved raw would record a fit RMS the saved patch never achieved and
    // stage a snapshot the roaster must refuse. The pin itself carries the apply contract.
    const baseline = { fanCoolingCPerMinAt10: 0.3, coolingFanCPerMinAt10: 350 }
    expect(baselinePinnedAirflow(baseline)).toEqual({ fanCoolingCPerMinAt10: 0.5, coolingFanCPerMinAt10: 300 })
    const pinnedFit = fitCoefficientsFromLog([source], defaultCalibration, {
      frozen: baselinePinnedAirflow(baseline),
      checkIdentifiability: false,
    })!
    expect(pinnedFit.coefficients.fanCoolingCPerMinAt10).toBe(0.5)
    expect(pinnedFit.coefficients.coolingFanCPerMinAt10).toBe(300)
    expect(combineSegmentedCalibration(pinnedFit, baseline)).toEqual(pinnedFit.coefficients)
    expect(
      pooledRms([source], { ...defaultCalibration, ...combineSegmentedCalibration(pinnedFit, baseline) }),
    ).toBeCloseTo(pinnedFit.rmsC, 6)
  })

  it('declines a loaded roast shorter than its turnaround exclusion instead of fitting Infinity', () => {
    const short = syntheticLog(TRUTH, 225, [{ fan: 6, heat: 8, seconds: 120 }])
    const fitOfShort = fitCoefficientsFromLog(
      [{ id: 's', label: 's', samples: short, massG: 225, ambientC: AMBIENT, scoreFromSec: 180 }],
      defaultCalibration,
    )
    expect(fitOfShort).toBeUndefined()
  })

  it('does not report a frozen value resting on a bound as a search collision', () => {
    const bounded = fitCoefficientsFromLog([source], defaultCalibration, {
      frozen: { fanCoolingCPerMinAt10: COEFFICIENT_BOUNDS.fanCoolingCPerMinAt10.min },
      checkIdentifiability: false,
    })!
    expect(bounded.coefficients.fanCoolingCPerMinAt10).toBe(COEFFICIENT_BOUNDS.fanCoolingCPerMinAt10.min)
    expect(bounded.pinned).not.toContain('fanCoolingCPerMinAt10')
  })

  /**
   * An empty chamber reads heating-mode airflow several times weaker than a bean bed does. Pinning
   * that value made the Journey law move Fan as if each level were worth a fifth of its real effect.
   */
  describe('fitting against a baseline whose heating-mode airflow is a chamber value', () => {
    const chamber = { fanCoolingCPerMinAt10: 3, coolingFanCPerMinAt10: TRUTH.coolingFanCPerMinAt10 }

    it('fits heating-mode airflow from roasts that vary Fan at constant Heat', () => {
      const result = fitAgainstBaseline([source], defaultCalibration, chamber)!
      expect(result.frozen).toEqual(['coolingFanCPerMinAt10'])
      expect(heatingAirflowResolved(result)).toBe(true)
      const relative =
        Math.abs(result.coefficients.fanCoolingCPerMinAt10 - TRUTH.fanCoolingCPerMinAt10) / TRUTH.fanCoolingCPerMinAt10
      expect(relative).toBeLessThan(0.2)
      expect(result.coefficients.coolingFanCPerMinAt10).toBe(TRUTH.coolingFanCPerMinAt10)
      const pinned = fitCoefficientsFromLog([source], defaultCalibration, { frozen: baselinePinnedAirflow(chamber) })!
      expect(result.rmsC).toBeLessThan(pinned.rmsC)
      // The saved patch is the set that was scored.
      expect(combineSegmentedCalibration(result, chamber)).toEqual(result.coefficients)
    })

    it('keeps the chamber value when the roasts cannot resolve heating-mode airflow', () => {
      const plainSource = {
        id: 'p',
        label: 'p',
        samples: syntheticLog(TRUTH, 225, PLAIN),
        massG: 225,
        ambientC: AMBIENT,
      }
      const result = fitAgainstBaseline([plainSource], defaultCalibration, chamber)!
      expect(result.frozen).toEqual(['fanCoolingCPerMinAt10', 'coolingFanCPerMinAt10'])
      expect(result.coefficients.fanCoolingCPerMinAt10).toBe(3)
      expect(combineSegmentedCalibration(result, chamber)).toEqual(result.coefficients)
    })

    it('pins both airflow terms when identifiability is not probed', () => {
      const result = fitAgainstBaseline([source], defaultCalibration, chamber, { checkIdentifiability: false })!
      expect(result.frozen).toEqual(['fanCoolingCPerMinAt10', 'coolingFanCPerMinAt10'])
      expect(result.coefficients.fanCoolingCPerMinAt10).toBe(3)
    })

    it('fits every airflow term the baseline did not measure', () => {
      const result = fitAgainstBaseline([source], defaultCalibration, {})!
      expect(result.frozen).toEqual([])
    })
  })

  it('treats an unstable airflow term as resolved only when baseline evidence supplied it', () => {
    const unstable = { ...fit, unstable: ['fanCoolingCPerMinAt10' as const] }
    expect(unresolvedUnstableFields(unstable, {})).toEqual(['fanCoolingCPerMinAt10'])
    expect(unresolvedUnstableFields(unstable, { fanCoolingCPerMinAt10: 12 })).toEqual([])
  })
})
